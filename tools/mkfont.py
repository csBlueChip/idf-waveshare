#!/usr/bin/env python3
"""
Generate a font_<symbol>.c for the wavedemo font registry (src/font.h).

Usage:
  tools/mkfont.py <ttf> <size> <symbol> "<display name>" fw|prop [lead] [outdir]

  fw    every glyph has the same width (rounded advance of 'M', made even)
  prop  each glyph has its own width (its rounded advance)

Glyphs: ASCII 0x20..0x7E, 4-bit anti-aliased (0 = background, 15 = ink),
'height' rows of ceil(width/2) bytes, high nibble = left pixel.
Then add the font to s_fonts[] in src/font.c and to src/CMakeLists.txt.

Examples (the two shipped fonts):
  tools/mkfont.py /usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf 20 mono "DejaVu Sans Mono" fw
  tools/mkfont.py /usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf 21 serif "Liberation Serif" prop

Needs: pip install pillow
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

if len(sys.argv) < 6:
	sys.exit(__doc__)

TTF, SIZE, SYM, NAME, MODE = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
LEAD  = int(sys.argv[6]) if len(sys.argv) > 6 else 2
OUT   = sys.argv[7] if len(sys.argv) > 7 else os.path.join(os.path.dirname(__file__), "..", "src")
FIRST, LAST = 0x20, 0x7E
if MODE not in ("fw", "prop"):
	sys.exit("mode must be fw or prop")

font = ImageFont.truetype(TTF, SIZE)
ascent, descent = font.getmetrics()
height = ascent + descent

if MODE == "fw":
	cell = int(round(font.getlength("M")))
	cell += cell & 1


def width_of(ch):
	return cell if MODE == "fw" else max(1, int(round(font.getlength(ch))))


def render(ch):
	w = width_of(ch)
	img = Image.new("L", (w, height), 0)
	ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
	px = [int(round(v * 15 / 255)) for v in img.tobytes()]
	rowBytes = (w + 1) // 2
	out = bytearray()
	for y in range(height):
		row = px[y * w:(y + 1) * w] + [0]		# pad odd width
		out += bytes((row[i] << 4) | row[i + 1] for i in range(0, rowBytes * 2, 2))
	return w, bytes(out)


chars   = [chr(c) for c in range(FIRST, LAST + 1)]
glyphs  = [render(ch) for ch in chars]
widths  = [w for w, _ in glyphs]
offsets = []
data    = bytearray()
for _, g in glyphs:
	offsets.append(len(data))
	data += g


def label(ch):
	return {"\\": "\\\\", "'": "\\'"}.get(ch, ch)


path = os.path.join(OUT, f"font_{SYM}.c")
with open(path, "w") as f:
	f.write(f"""/*
 * GENERATED by tools/mkfont.py - do not edit.
 * {os.path.basename(TTF)} {SIZE}px, {MODE}, {height}px high, baseline {ascent}.
 *
 * Glyph data rendered from the font named above; see its licence
 * (DejaVu: Bitstream Vera licence; Liberation: SIL Open Font License 1.1).
 */

#include "font.h"

static const uint8_t s_widths[] = {{
""")
	for i in range(0, len(widths), 16):
		f.write("\t" + ", ".join(str(w) for w in widths[i:i + 16]) + ",\n")
	f.write("};\n\nstatic const uint32_t s_offsets[] = {\n")
	for i in range(0, len(offsets), 8):
		f.write("\t" + ", ".join(str(o) for o in offsets[i:i + 8]) + ",\n")
	f.write("};\n\nstatic const uint8_t s_data[] = {\n")
	for ch, (w, g) in zip(chars, glyphs):
		f.write(f"\t/* '{label(ch)}' w{w} */\n")
		rb = (w + 1) // 2
		for y in range(height):
			f.write("\t" + ", ".join(f"0x{b:02X}" for b in g[y * rb:(y + 1) * rb]) + ",\n")
	f.write(f"""}};

const font_t font_{SYM} = {{
	.name     = "{NAME}",
	.height   = {height},
	.baseline = {ascent},
	.lead     = {LEAD},
	.maxWidth = {max(widths)},
	.prop     = {"true" if MODE == "prop" else "false"},
	.first    = 0x{FIRST:02X},
	.last     = 0x{LAST:02X},
	.widths   = s_widths,
	.offsets  = s_offsets,
	.data     = s_data,
}};
""")

print(f"{NAME}: {MODE}, {height}px high, baseline {ascent}, widths {min(widths)}..{max(widths)}, "
      f"{len(data)} bytes -> {path}")
